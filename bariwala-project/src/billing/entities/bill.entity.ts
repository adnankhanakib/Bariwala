import { Column, CreateDateColumn, Entity, PrimaryColumn, PrimaryGeneratedColumn, UpdateDateColumn } from "typeorm";
@Entity('bill')
export class Bill{
    @PrimaryGeneratedColumn()
    id:number;
    @Column()
    month:string;
    @Column({
        type:'int'
    })
    rent:Number;
    @Column({
        type:'int'
    })
    gas:Number;
    @Column({
        type:'int'
    })
    water:Number;
    @Column({
        type:'int'
    })
    electricity:Number;
    @Column({
        type:'int'
    })
    total:Number;
    @Column({
        type:'date'
    })
    due_date:Date;
    @CreateDateColumn()
    createdAt:Date;
    @UpdateDateColumn()
    updatedAt:Date;
}